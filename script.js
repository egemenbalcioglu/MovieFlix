var slider =
document.querySelector(".slider");

var sliderTitle =
document.getElementById("sliderTitle");

var sliderDesc =
document.getElementById("sliderDesc");




var currentSlide = 0;




function changeSlider(){

  slider.style.backgroundImage =
  "url('" + sliderItems[currentSlide].image + "')";

  sliderTitle.innerText =
  sliderItems[currentSlide].title;

  sliderDesc.innerText =
  sliderItems[currentSlide].desc;

  currentSlide++;

  if(currentSlide >= sliderItems.length){

    currentSlide = 0;
  }

}



changeSlider();


setInterval(changeSlider, 5000);

var movieList = document.getElementById("movieList");

var search = document.getElementById("search");

var modal = document.getElementById("modal");

var closeBtn = document.getElementById("close");

var modalImg = document.getElementById("modalImg");

var modalTitle = document.getElementById("modalTitle");

var modalDesc = document.getElementById("modalDesc");

var seriesList = document.getElementById("seriesList");



function showMovies(movieArray){

  movieList.innerHTML = "";

  for(var i = 0; i < movieArray.length; i++){

    movieList.innerHTML += `

      <div class="movie-card" onclick="openModal(${i})">

        <img src="${movieArray[i].image}">

        <div class="movie-info">

          <h3>${movieArray[i].name}</h3>

        </div>

      </div>

    `;
  }

}


function showSeries(){

  seriesList.innerHTML = "";

  for(var i = 0; i < series.length; i++){

    seriesList.innerHTML += `

      <div class="movie-card"
      onclick="openSeriesModal(${i})">

        <img src="${series[i].image}">

        <div class="movie-info">

          <h3>${series[i].name}</h3>

        </div>

      </div>

    `;
  }

}

function openSeriesModal(index){

  modal.style.display = "flex";

  modalImg.src = series[index].image;

  modalTitle.innerText = series[index].name;

  modalDesc.innerText = series[index].description;

}
function openModal(index){

  modal.style.display = "flex";

  modalImg.src = movies[index].image;

  modalTitle.innerText = movies[index].name;

  modalDesc.innerText = movies[index].description;

}



closeBtn.onclick = function(){

  modal.style.display = "none";

}


search.addEventListener("keyup", function(){

  var text = search.value.toLowerCase();

  var filteredMovies = [];

  for(var i = 0; i < movies.length; i++){

    if(movies[i].name.toLowerCase().includes(text)){

      filteredMovies.push(movies[i]);

    }

  }

  showMovies(filteredMovies);

});



showMovies(movies);
