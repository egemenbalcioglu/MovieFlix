var popularContainer = document.getElementById("popularContainer");
var sortSelect = document.getElementById("sortSelect");

var modal = document.getElementById("modal");
var closeBtn = document.getElementById("close");

var modalImg = document.getElementById("modalImg");
var modalTitle = document.getElementById("modalTitle");
var modalDesc = document.getElementById("modalDesc");

var modalType = document.getElementById("modalType");
var modalRating = document.getElementById("modalRating");
var modalPopularity = document.getElementById("modalPopularity");


function showPopular(items){

  popularContainer.innerHTML = "";

  for(var i = 0; i < items.length; i++){

    popularContainer.innerHTML += `

      <div class="popular-card" onclick="openModal(${i})">

        <img src="${items[i].image}">

        <div class="popular-info">

          <span class="badge">${items[i].type}</span>

          <h3>${items[i].name}</h3>

          <p>${items[i].year}</p>

          <p class="rating">⭐ IMDb ${items[i].imdb}</p>

          <p>${items[i].popularity}</p>

        </div>

      </div>

    `;
  }

}



function openModal(index){

  modal.style.display = "flex";

  modalImg.src = popularItems[index].image;
  modalTitle.innerText = popularItems[index].name;
  modalDesc.innerText = popularItems[index].description;

  modalType.innerText = popularItems[index].type;
  modalRating.innerText = "IMDb " + popularItems[index].imdb;
  modalPopularity.innerText = popularItems[index].popularity;
}

closeBtn.onclick = function(){

  modal.style.display = "none";
}

sortSelect.addEventListener("change", function(){

  var selected = sortSelect.value;

  var sortedItems = popularItems.slice();

  if(selected == "high"){

    sortedItems.sort(function(a, b){
      return b.imdb - a.imdb;
    });

  }

  else if(selected == "low"){

    sortedItems.sort(function(a, b){
      return a.imdb - b.imdb;
    });

  }

  showPopular(sortedItems);

});

showPopular(popularItems);